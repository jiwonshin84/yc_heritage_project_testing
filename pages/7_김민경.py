import pandas as pd
import re
from datetime import datetime

# =====================================================
# 현재 연도
# =====================================================

CURRENT_YEAR = datetime.now().year

# =====================================================
# 1. 원본 문화재 상세 데이터 불러오기
# =====================================================

heritage_df = pd.read_csv(

    "/content/drive/MyDrive/"
    "00. 2026학년도 인재양성프로젝트/"
    "공공데이터 기반 프로젝트/"
    "dataset/영천_국가유산_상세_좌표보완.csv"

)

# =====================================================
# 컬럼 공백 제거
# =====================================================

heritage_df.columns = (
    heritage_df.columns.str.strip()
)

# =====================================================
# 2. 위험 분석 핵심 컬럼만 추출
# =====================================================

feature_df = heritage_df[[

    # -----------------------------
    # 기본키
    # -----------------------------

    "국가유산연계번호",

    # -----------------------------
    # 문화재명
    # -----------------------------

    "문화재명(국문)",

    # -----------------------------
    # 문화재 종목
    # -----------------------------

    "국가유산종목",

    # -----------------------------
    # 시대
    # -----------------------------

    "시대",

    # -----------------------------
    # 위치정보
    # -----------------------------

    "위도",
    "경도"

]].copy()

# =====================================================
# 3. 시대 그룹화 함수
# =====================================================

def simplify_era(text):

    if pd.isna(text):
        return "기타"

    text = str(text).strip()

    # -------------------------------------------------
    # 청동기
    # -------------------------------------------------

    if "청동기" in text:
        return "청동기"

    # -------------------------------------------------
    # 신라
    # -------------------------------------------------

    elif (
        "통일신라" in text or
        "신라시대 후기" in text
    ):
        return "통일신라"

    elif "신라" in text:
        return "신라"

    # -------------------------------------------------
    # 고려
    # -------------------------------------------------

    elif (
        "고려시대 초기" in text or
        "고려 초기" in text
    ):
        return "고려초기"

    elif (
        "고려시대 말기" in text or
        "고려 말기" in text
    ):
        return "고려후기"

    elif "고려" in text:
        return "고려"

    # -------------------------------------------------
    # 조선 초기
    # -------------------------------------------------

    elif (
        "세종" in text or
        "태조" in text or
        "태종" in text or
        "세조" in text or
        "성종" in text or
        "중종" in text or
        "인종" in text
    ):
        return "조선초기"

    # -------------------------------------------------
    # 조선 후기
    # -------------------------------------------------

    elif (
        "숙종" in text or
        "영조" in text or
        "정조" in text or
        "순조" in text or
        "철종" in text or
        "고종" in text or
        "광해군" in text
    ):
        return "조선후기"

    # -------------------------------------------------
    # 조선 직접 표기
    # -------------------------------------------------

    elif (
        "조선시대 후기" in text or
        "조선 후기" in text
    ):
        return "조선후기"

    elif "조선" in text:
        return "조선"

    # -------------------------------------------------
    # 대한제국
    # -------------------------------------------------

    elif "대한제국" in text:
        return "대한제국"

    # -------------------------------------------------
    # 연도 기반 추정
    # -------------------------------------------------

    year_match = re.search(
        r"\d{4}",
        text
    )

    if year_match:

        year = int(
            year_match.group()
        )

        if year < 700:
            return "신라"

        elif year < 1400:
            return "고려"

        elif year < 1600:
            return "조선초기"

        elif year < 1910:
            return "조선후기"

    return "기타"

# =====================================================
# 4. 시대그룹 컬럼 생성
# =====================================================

feature_df["시대그룹"] = (
    feature_df["시대"]
    .apply(simplify_era)
)

# =====================================================
# 5. 시대별 추정 제작연도 매핑
# =====================================================

era_year_map = {

    "청동기": -1000,

    "신라": 600,
    "통일신라": 800,

    "고려초기": 1100,
    "고려": 1200,
    "고려후기": 1350,

    "조선초기": 1500,
    "조선": 1650,
    "조선후기": 1750,

    "대한제국": 1900,

    "기타": 1900

}

# =====================================================
# 6. 추정 제작연도 생성
# =====================================================

feature_df["추정제작연도"] = (
    feature_df["시대그룹"]
    .map(era_year_map)
)

# =====================================================
# 7. 문화재 연령 계산
# =====================================================

feature_df["문화재연령"] = (

    CURRENT_YEAR
    - feature_df["추정제작연도"]

)

# =====================================================
# 8. 재질 / 노출형태 기본값
# =====================================================

feature_df["재질"] = "기타"
feature_df["노출형태"] = "반실외"

# =====================================================
# 9. 재질 분류 키워드
# =====================================================

# -----------------------------
# 석조
# -----------------------------

stone_keywords = [

    "석탑",
    "석조",
    "석불",
    "비",
    "암각화",
    "태실",
    "옥비",
    "봉수"

]

# -----------------------------
# 목조
# -----------------------------

wood_keywords = [

    "고택",
    "서원",
    "향교",
    "정",
    "당",
    "각",
    "재",
    "대웅전",
    "종택",
    "사당",
    "누각",
    "교회"

]

# -----------------------------
# 금속
# -----------------------------

metal_keywords = [

    "철조",
    "금동",
    "청동",
    "범종",
    "북"

]

# -----------------------------
# 회화
# -----------------------------

painting_keywords = [

    "탱화",
    "괘불",
    "초상",
    "영정",
    "불화",
    "도"

]

# =====================================================
# 10. 재질 자동 분류
# =====================================================

for idx, row in feature_df.iterrows():

    name = str(
        row["문화재명(국문)"]
    )

    # -----------------------------
    # 석조
    # -----------------------------

    if any(
        keyword in name
        for keyword in stone_keywords
    ):

        feature_df.loc[idx, "재질"] = "석조"

    # -----------------------------
    # 목조
    # -----------------------------

    elif any(
        keyword in name
        for keyword in wood_keywords
    ):

        feature_df.loc[idx, "재질"] = "목조"

    # -----------------------------
    # 금속
    # -----------------------------

    elif any(
        keyword in name
        for keyword in metal_keywords
    ):

        feature_df.loc[idx, "재질"] = "금속"

    # -----------------------------
    # 회화
    # -----------------------------

    elif any(
        keyword in name
        for keyword in painting_keywords
    ):

        feature_df.loc[idx, "재질"] = "회화"

# =====================================================
# 11. 노출형태 키워드
# =====================================================

# -----------------------------
# 실내
# -----------------------------

indoor_keywords = [

    "탱화",
    "괘불",
    "초상",
    "영정",
    "불화",
    "북",
    "불상"

]

# -----------------------------
# 실외
# -----------------------------

outdoor_keywords = [

    "석탑",
    "비",
    "암각화",
    "봉수",
    "태실"

]

# =====================================================
# 12. 노출형태 자동 분류
# =====================================================

for idx, row in feature_df.iterrows():

    name = str(
        row["문화재명(국문)"]
    )

    # -----------------------------
    # 실내
    # -----------------------------

    if any(
        keyword in name
        for keyword in indoor_keywords
    ):

        feature_df.loc[idx, "노출형태"] = "실내"

    # -----------------------------
    # 실외
    # -----------------------------

    elif any(
        keyword in name
        for keyword in outdoor_keywords
    ):

        feature_df.loc[idx, "노출형태"] = "실외"

    # -----------------------------
    # 나머지
    # -----------------------------

    else:

        feature_df.loc[idx, "노출형태"] = "반실외"

# =====================================================
# 13. 최종 컬럼 순서 정리
# =====================================================

feature_df = feature_df[[

    "국가유산연계번호",
    "문화재명(국문)",
    "국가유산종목",

    "시대그룹",
    "추정제작연도",
    "문화재연령",

    "재질",
    "노출형태",

    "위도",
    "경도"

]]

